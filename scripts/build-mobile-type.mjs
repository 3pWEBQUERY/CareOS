// Generates app/styles/39-mobile-type.css: on phones (≤ 960 px) every font size below
// 11 px is raised, so text stays readable. Desktop sizes are untouched.
// Run after changing font sizes in the styles:  node scripts/build-mobile-type.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import postcss from "postcss";

const root = path.resolve(import.meta.dirname, "..");
const output = path.join(root, "app/styles/39-mobile-type.css");
const MOBILE = 960;

// Badges, keyboard hints and desktop-only chrome keep their compact size.
const EXCLUDE = /badge|kbd|sidebar|topbar|tooltip|rail|flyout|(^|[\s>+~])(i|sup|sub)\b/;

const bump = (px) => (px < 9 ? 11 : px < 10 ? 11.5 : 12);

// Global styles in cascade order, then the component styles imported by pages.
const globals = readFileSync(path.join(root, "app/globals.css"), "utf8");
const styleFiles = [...globals.matchAll(/@import "\.\/(styles\/[^"]+)"/g)]
  .map((match) => path.join(root, "app", match[1]))
  .filter((file) => !file.endsWith(path.basename(output)));
const componentFiles = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const file = path.join(dir, name);
    if (statSync(file).isDirectory()) {
      if (name !== "styles" && name !== "api") walk(file);
    } else if (name.endsWith(".css") && name !== "globals.css") componentFiles.push(file);
  }
})(path.join(root, "app"));

function mediaChain(node) {
  const chain = [];
  for (let parent = node.parent; parent; parent = parent.parent)
    if (parent.type === "atrule" && parent.name === "media") chain.unshift(parent.params);
  return chain;
}

// A media chain that applies on phones: no min-width, no print, max-widths not above the phone range.
function onPhones(chain) {
  return chain.every((params) => !/min-width|print/.test(params));
}
const phoneOnly = (chain) =>
  chain.some((params) => {
    const max = /max-width:\s*(\d+)px/.exec(params);
    return max && Number(max[1]) <= MOBILE;
  });

const small = [];
const tunedForPhones = new Set();
for (const [files, raise] of [
  [styleFiles, false],
  [componentFiles, true],
]) {
  for (const file of files) {
    const css = postcss.parse(readFileSync(file, "utf8"), { from: file });
    css.walkDecls("font-size", (decl) => {
      const rule = decl.parent;
      if (rule.type !== "rule") return;
      const chain = mediaChain(rule);
      if (!onPhones(chain)) return;
      const px = /^(\d+(?:\.\d+)?)px$/.exec(decl.value.trim());
      const value = px ? Number(px[1]) : null;
      for (const selector of rule.selectors) {
        if (phoneOnly(chain) && (value === null || value >= 11)) tunedForPhones.add(selector);
        if (value !== null && value < 11 && !EXCLUDE.test(selector))
          small.push({ selector, chain, size: bump(value), raise, phone: phoneOnly(chain) });
      }
    });
  }
}

// Selectors already sized for phones keep that size.
const entries = small.filter((entry) => entry.phone || !tunedForPhones.has(entry.selector));
const groups = new Map();
for (const entry of entries) {
  const key = entry.chain.join(" | ");
  const selector = entry.raise && !/^(html|:root)/.test(entry.selector) ? `:root ${entry.selector}` : entry.selector;
  if (!groups.has(key)) groups.set(key, new Map());
  groups.get(key).set(selector, entry.size);
}

let out = "/* Generated by scripts/build-mobile-type.mjs – do not edit. Raises font sizes below 11px on phones. */\n";
out += `@media (max-width: ${MOBILE}px) {\n`;
for (const [key, rules] of groups) {
  const indent = key ? "    " : "  ";
  if (key) out += `  @media ${key.split(" | ").join(" and ")} {\n`;
  for (const [selector, size] of rules) out += `${indent}${selector} {\n${indent}  font-size: ${size}px;\n${indent}}\n`;
  if (key) out += "  }\n";
}
out += "}\n";
writeFileSync(output, out);
console.log(`${entries.length} font sizes raised in ${path.relative(root, output)}`);
